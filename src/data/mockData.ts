const STORAGE_KEYS = {
  BOOKINGS: 'voyagedesk_bookings_v1',
  CLIENTS: 'voyagedesk_clients_v1',
  INVOICES: 'voyagedesk_invoices_v1',
  ITINERARIES: 'voyagedesk_itineraries_v1',
  SETTINGS: 'voyagedesk_settings_v1',
};

export function loadSavedData() {
  try {
    const rawBookings = localStorage.getItem(STORAGE_KEYS.BOOKINGS);
    const rawClients = localStorage.getItem(STORAGE_KEYS.CLIENTS);
    const rawInvoices = localStorage.getItem(STORAGE_KEYS.INVOICES);
    const rawItineraries = localStorage.getItem(STORAGE_KEYS.ITINERARIES);
    const rawSettings = localStorage.getItem(STORAGE_KEYS.SETTINGS);

    return {
      bookings: rawBookings ? JSON.parse(rawBookings) : INITIAL_BOOKINGS,
      clients: rawClients ? JSON.parse(rawClients) : INITIAL_CLIENTS,
      invoices: rawInvoices ? JSON.parse(rawInvoices) : INITIAL_INVOICES,
      itineraries: rawItineraries ? JSON.parse(rawItineraries) : INITIAL_ITINERARIES,
      settings: rawSettings ? JSON.parse(rawSettings) : DEFAULT_AGENCY_SETTINGS,
    };
  } catch (e) {
    console.error('Failed to parse localStorage data, falling back to initial data', e);
    return {
      bookings: INITIAL_BOOKINGS,
      clients: INITIAL_CLIENTS,
      invoices: INITIAL_INVOICES,
      itineraries: INITIAL_ITINERARIES,
      settings: DEFAULT_AGENCY_SETTINGS,
    };
  }
}

export function saveAllData(data: {
  bookings: Booking[];
  clients: ClientTraveler[];
  invoices: Invoice[];
  itineraries: Itinerary[];
  settings: AgencySettings;
}) {
  try {
    localStorage.setItem(STORAGE_KEYS.BOOKINGS, JSON.stringify(data.bookings));
    localStorage.setItem(STORAGE_KEYS.CLIENTS, JSON.stringify(data.clients));
    localStorage.setItem(STORAGE_KEYS.INVOICES, JSON.stringify(data.invoices));
    localStorage.setItem(STORAGE_KEYS.ITINERARIES, JSON.stringify(data.itineraries));
    localStorage.setItem(STORAGE_KEYS.SETTINGS, JSON.stringify(data.settings));
  } catch (e) {
    console.error('Failed to save to localStorage', e);
  }
}

export function resetDemoData() {
  localStorage.removeItem(STORAGE_KEYS.BOOKINGS);
  localStorage.removeItem(STORAGE_KEYS.CLIENTS);
  localStorage.removeItem(STORAGE_KEYS.INVOICES);
  localStorage.removeItem(STORAGE_KEYS.ITINERARIES);
  localStorage.removeItem(STORAGE_KEYS.SETTINGS);
}
